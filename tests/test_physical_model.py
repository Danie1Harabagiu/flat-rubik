"""Independent audit against Herbert Kociemba's published facelet conventions.

Reference: https://kociemba.org/math/CubeDefs.htm (FaceletMove, CF, EF).
Cycles below are fixed reference data, not generated by Cube.move/rotate.
Only the adapter maps the production coordinates to standard U1..B9 labels.
Tests run offline, without installing a solver or trusting production inverses.
"""
import random
import unittest
from collections import Counter

from flat_rubik.cube import Cube, FACE_COLORS
from flat_rubik.projection import project
from flat_rubik.state import cube_from_facelets

FACES = "URFDLB"
COLORS = dict(zip(FACES, ("galben", "verde", "rosu", "alb", "albastru", "portocaliu")))
STRIPS = {
    "U": ("R1 F1 L1 B1", "R2 F2 L2 B2", "R3 F3 L3 B3"),
    "R": ("U3 B7 D3 F3", "U6 B4 D6 F6", "U9 B1 D9 F9"),
    "F": ("U7 R1 D3 L9", "U8 R4 D2 L6", "U9 R7 D1 L3"),
    "D": ("R7 B7 L7 F7", "R8 B8 L8 F8", "R9 B9 L9 F9"),
    "L": ("U1 F1 D1 B9", "U4 F4 D4 B6", "U7 F7 D7 B3"),
    "B": ("U1 L7 D9 R3", "U2 L4 D8 R6", "U3 L1 D7 R9"),
}
CORNER_SLOTS = tuple(s.split() for s in ("U9 R1 F3", "U7 F1 L3", "U1 L1 B3", "U3 B1 R3",
                                         "D3 F9 R7", "D1 L9 F7", "D7 B9 L7", "D9 R9 B7"))
EDGE_SLOTS = tuple(s.split() for s in ("U6 R2", "U8 F2", "U4 L2", "U2 B2", "D6 R8", "D2 F8",
                                       "D4 L8", "D8 B8", "F6 R4", "F4 L6", "B6 L4", "B4 R6"))


def standard_slots():
    result = {}
    for row in range(3):
        for col in range(3):
            # Each face is numbered left-to-right, top-to-bottom, viewed
            # from outside, with the standard URFDLB unfolded orientation.
            coords = {
                "U": ((col - 1, 1, row - 1), (0, 1, 0)),
                "R": ((1, 1 - row, 1 - col), (1, 0, 0)),
                "F": ((col - 1, 1 - row, 1), (0, 0, 1)),
                "D": ((col - 1, -1, 1 - row), (0, -1, 0)),
                "L": ((-1, 1 - row, col - 1), (-1, 0, 0)),
                "B": ((1 - col, 1 - row, -1), (0, 0, -1)),
            }
            for face in FACES:
                result[f"{face}{row * 3 + col + 1}"] = coords[face]
    return result


SLOTS = standard_slots()
LABEL_FOR_SLOT = {slot: label for label, slot in SLOTS.items()}
ORIGINS = {(c.id, color): LABEL_FOR_SLOT[c.position, n]
           for c in Cube().cubies for n, color in c.stickers.items()}


def actual_labels(cube):
    return {LABEL_FOR_SLOT[c.position, n]: ORIGINS[c.id, color]
            for c in cube.cubies for n, color in c.stickers.items()}


def reference_turn(labels, move):
    face = move[0]
    turns = {"": 1, "'": 3, "2": 2}[move[1:]]
    cycles = [[f"{face}{n}" for n in (1, 3, 9, 7)], [f"{face}{n}" for n in (2, 6, 8, 4)]]
    cycles += [strip.split() for strip in STRIPS[face]]
    for _ in range(turns):
        before = labels.copy()
        for cycle in cycles:
            for src, dst in zip(cycle, cycle[1:] + cycle[:1]):
                labels[dst] = before[src]


def parity(permutation):
    return sum(permutation[i] > permutation[j] for i in range(len(permutation))
               for j in range(i + 1, len(permutation))) % 2


class PhysicalModelTests(unittest.TestCase):
    def test_all_18_moves_match_independent_reference(self):
        self.assertEqual(FACE_COLORS, COLORS)
        for face in FACES:
            for suffix in ("", "'", "2"):
                cube = Cube()
                reference = {label: label for label in SLOTS}
                reference_turn(reference, face + suffix)
                cube.move(face + suffix)
                self.assertEqual(actual_labels(cube), reference, face + suffix)

    def test_all_324_pairs_match_reference(self):
        moves = [f + s for f in FACES for s in ("", "'", "2")]
        for a in moves:
            for b in moves:
                cube = Cube()
                reference = {label: label for label in SLOTS}
                for move in (a, b):
                    cube.move(move)
                    reference_turn(reference, move)
                self.assertEqual(actual_labels(cube), reference, (a, b))

    def test_5000_steps_match_all_54_sticker_identities(self):
        rng = random.Random(20261106)
        cube = Cube()
        reference = {label: label for label in SLOTS}
        for step in range(5000):
            move = rng.choice(FACES) + rng.choice(("", "'", "2"))
            cube.move(move)
            reference_turn(reference, move)
            self.assertEqual(actual_labels(cube), reference, (step, move))

    def test_exact_physical_layer_membership(self):
        for face in FACES:
            cube = Cube()
            before = {c.id: (c.position, c.stickers.copy()) for c in cube.cubies}
            cube.move(face)
            changed = [c for c in cube.cubies if before[c.id] != (c.position, c.stickers)]
            self.assertEqual(Counter(c.kind for c in changed), {"corner": 4, "edge": 4})
            labels = actual_labels(cube)
            self.assertEqual(sum(k != v for k, v in labels.items()), 20)
            for f in FACES:
                self.assertEqual(labels[f + "5"], f + "5")

    def test_circular_projection_preserves_reference_piece_groups(self):
        cube = Cube()
        cube.apply("R U F' L2 B D R2 F U'")
        reference = {label: label for label in SLOTS}
        for move in "R U F' L2 B D R2 F U'".split():
            reference_turn(reference, move)
        views = project(cube)
        self.assertEqual(len(views), 54)
        self.assertEqual({LABEL_FOR_SLOT[s.position, s.normal]: ORIGINS[s.cubie_id, s.color]
                          for s in views}, reference)
        for group in (*CORNER_SLOTS, *EDGE_SLOTS):
            positions = {SLOTS[label][0] for label in group}
            self.assertEqual(len(positions), 1)
            ids = {s.cubie_id for s in views if s.position in positions}
            self.assertEqual(len(ids), 1)

    def test_import_1000_independently_generated_legal_states(self):
        rng = random.Random(87)
        for _ in range(1000):
            cp, ep = list(range(8)), list(range(12))
            rng.shuffle(cp)
            rng.shuffle(ep)
            if parity(cp) != parity(ep):
                ep[0], ep[1] = ep[1], ep[0]
            co, eo = [rng.randrange(3) for _ in range(7)], [rng.randrange(2) for _ in range(11)]
            co.append(-sum(co) % 3)
            eo.append(sum(eo) % 2)
            reference = {label: label for label in SLOTS}
            for groups, perm, orientation in ((CORNER_SLOTS, cp, co), (EDGE_SLOTS, ep, eo)):
                for slot, piece in enumerate(perm):
                    for k, origin in enumerate(groups[piece]):
                        destination = groups[slot][(k + orientation[slot]) % len(groups[slot])]
                        reference[destination] = origin
            colors = {SLOTS[slot]: COLORS[origin[0]] for slot, origin in reference.items()}
            rebuilt = cube_from_facelets(colors)
            self.assertEqual(actual_labels(rebuilt), reference)
            # Re-importing a moved state must preserve physical identities too.
            rebuilt.move("R")
            reference_turn(reference, "R")
            self.assertEqual(actual_labels(rebuilt), reference)


if __name__ == "__main__":
    unittest.main()
